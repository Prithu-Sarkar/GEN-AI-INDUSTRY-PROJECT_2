# Effect sizes (Cohen's d)
def cohen_d(x,y):
    n1,n2=len(x),len(y)
    p=np.sqrt(((n1-1)*x.std()**2+(n2-1)*y.std()**2)/(n1+n2-2))
    return (x.mean()-y.mean())/p
