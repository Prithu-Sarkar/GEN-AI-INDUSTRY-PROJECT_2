# IQR method
def iqr_outliers(df, cols):
    mask = pd.Series([False]*len(df))
    for c in cols:
        q1, q3 = df[c].quantile(0.25), df[c].quantile(0.75)
        iqr = q3 - q1
        mask |= (df[c] < q1 - 1.5*iqr) | (df[c] > q3 + 1.5*iqr)
    return mask

