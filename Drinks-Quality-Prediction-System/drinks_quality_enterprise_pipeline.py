# Domain-driven interaction features
def engineer_features(df_in):
    df_out = df_in.copy()
    # Sulfur ratio (free / total)
    df_out["sulfur_ratio"]         = df_out["free_sulfur_dioxide"] / (df_out["total_sulfur_dioxide"] + 1e-9)
